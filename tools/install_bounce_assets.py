"""Install weapon_bounce_shotgun resources into Cremation.

The first-person model is the user's current shotgun, including its hands
and animations. Third-person and world models retain private shotgun
copies, so neither stock shotgun nor Ricochet assets are overwritten. The HUD
icon has its own descriptor and reuses the vanilla shell and grenade counters.
"""
from pathlib import Path
import hashlib, json, shutil, struct
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
MOD = ROOT / 'Cremation'

# destination in Cremation <- read-only source
COPIES = {
    'models/cremation/v_bounce_shotgun.mdl': 'Cremation/assets-source/additional_weapons/current_shotgun/v_shotgun.mdl',
    'models/cremation/p_bounce_shotgun.mdl': 'Cremation/assets-source/additional_weapons/current_shotgun/p_shotgun.mdl',
    'models/cremation/w_bounce_shotgun.mdl': 'Cremation/assets-source/additional_weapons/current_shotgun/w_shotgun.mdl',
    # The world model has zero embedded textures. GoldSrc derives this name
    # from the *installed* model path, so renaming only the mesh is incomplete.
    'models/cremation/w_bounce_shotgunT.mdl': 'Cremation/assets-source/additional_weapons/current_shotgun/w_shotgunt.mdl',
}

SPRITE_NAME = 'cremation_bounce_shotgun'
SPRITE_PATH = MOD / 'sprites' / f'{SPRITE_NAME}.spr'
TEXT_PATH = MOD / 'sprites' / 'weapon_bounce_shotgun.txt'
MANIFEST = MOD / 'bounce-assets.json'


def draw_icon() -> Image.Image:
    """128x32 HUD icon: shotgun silhouette plus two bounce arcs and a label."""
    image = Image.new('L', (128, 32), 0)
    draw = ImageDraw.Draw(image)
    # Shotgun: barrel, receiver, pump and stock.
    draw.rectangle((2, 9, 46, 12), fill=255)
    draw.rectangle((2, 13, 16, 20), fill=255)
    draw.polygon([(2, 20), (2, 25), (7, 25), (11, 20)], fill=255)
    draw.rectangle((34, 13, 45, 17), fill=255)
    draw.ellipse((39, 14, 43, 17), fill=0)
    # Two bounce arcs with impact marks.
    for start, end in (((50, 24), (62, 14)), ((62, 14), (76, 24))):
        draw.line((start, end), fill=255, width=2)
    for x, y in ((50, 24), (62, 14), (76, 24)):
        draw.ellipse((x - 2, y - 2, x + 2, y + 2), fill=255)
    try:
        font = ImageFont.truetype('C:/Windows/Fonts/arialbd.ttf', 14)
    except OSError:  # pragma: no cover - font is present on this host
        font = ImageFont.load_default()
    draw.text((78, 7), 'FLAK', font=font, fill=255)
    return image


def write_sprite(image: Image.Image) -> None:
    header = struct.pack('<4siiifiiifi', b'IDSP', 2, 2, 1, 66.0, 128, 32, 1, 0.0, 0)
    palette = bytes(value for index in range(256) for value in (index, index, index))
    # Frame: type 0 (SPR_SINGLE), origin (-64, 16), size 128x32, then indices.
    frame = struct.pack('<5i', 0, -64, 16, 128, 32) + image.tobytes()
    SPRITE_PATH.write_bytes(header + struct.pack('<H', 256) + palette + frame)


def write_descriptor() -> None:
    # Same layout the legacy client reads for every weapon (see ammo.cpp,
    # WeaponsResource::LoadWeaponSprites): one entry set per resolution.
    lines = ['10']
    for resolution, ammo, ammo2 in (
        ('320', '320hud2 76 72 18 18', '320hud2 36 16 18 18'),
        ('640', '640hud7 24 96 24 24', '640hud7 48 72 24 24'),
    ):
        lines.append(f'weapon\t\t\t{resolution} {SPRITE_NAME} 0 0 128 32')
        lines.append(f'weapon_s\t\t{resolution} {SPRITE_NAME} 0 0 128 32')
        lines.append(f'ammo\t\t\t{resolution} {ammo}')
        lines.append(f'crosshair\t\t{resolution} crosshairs 0 48 24 24')
        lines.append(f'autoaim\t\t\t{resolution} crosshairs 48 72 24 24')
    TEXT_PATH.write_text('\n'.join(lines) + '\n')


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def install() -> None:
    manifest = {}
    for destination, source in COPIES.items():
        target = MOD / destination
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / source, target)
        manifest[destination] = {
            'source': source,
            'sha256': sha256(target),
            'bytes': target.stat().st_size,
        }
    write_sprite(draw_icon())
    write_descriptor()
    manifest[f'sprites/{SPRITE_NAME}.spr'] = {
        'source': 'generated by tools/install_bounce_assets.py',
        'sha256': sha256(SPRITE_PATH),
        'bytes': SPRITE_PATH.stat().st_size,
    }
    manifest['sprites/weapon_bounce_shotgun.txt'] = {
        'source': 'generated by tools/install_bounce_assets.py',
        'sha256': sha256(TEXT_PATH),
        'bytes': TEXT_PATH.stat().st_size,
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Installed Bounce Shotgun models and HUD ({len(manifest)} files).')


if __name__ == '__main__':
    install()
