"""Extract every cultist vocal SFX from the user's Blood RFF into GoldSrc WAVs.
RFF/SFX layouts and event IDs documented from NBlood resource/ai/actor sources.
"""
from pathlib import Path
import struct,wave,math,json,hashlib,re
MOD=Path(__file__).resolve().parents[1]
BLOOD=Path('D:/SteamLibrary/steamapps/common/Blood')
EVENTS={'Alert':list(range(1003,1008))+list(range(4003,4008)),
        'Search':list(range(1008,1013))+list(range(4008,4013)),
        'Pain':list(range(1013,1018))+list(range(4013,4018)),
        'Death':list(range(1018,1021))+list(range(4018,4021)),
        'Victory':list(range(1021,1025))+list(range(4021,4025)),
        'Burning':[1031,1032,1033,4031,4032,4033]}
class Rff:
 def __init__(self,path):
  self.b=path.read_bytes();version,offset,count=struct.unpack_from('<H2xII',self.b,4)
  if self.b[:4]!=b'RFF\x1a':raise ValueError('Invalid RFF')
  table=bytearray(self.b[offset:offset+count*48])
  if version&0xff00==0x300:
   key=(offset*(1+(version&255)))&65535
   for i in range(len(table)):table[i]^=((key+i)>>1)&255
  self.byname={};self.byid={}
  for i in range(count):
   at=i*48;position,size=struct.unpack_from('<II',table,at+16);flags=table[at+32]
   kind=table[at+33:at+36].decode('ascii');name=table[at+36:at+44].split(b'\0')[0].decode('ascii')
   ident=struct.unpack_from('<i',table,at+44)[0];entry=(position,size,flags,name)
   self.byname[(kind,name.upper())]=entry
   if flags&1:self.byid[(kind,ident)]=entry
 def read(self,entry):
  offset,size,flags,_=entry;data=bytearray(self.b[offset:offset+size])
  if flags&16:
   for i in range(min(256,len(data))):data[i]^=i>>1
  return data

def install():
 rff=Rff(BLOOD/'sounds.rff');report=[];header=[]
 out=MOD/'sound/blood/cultist';out.mkdir(parents=True,exist_ok=True)
 rawout=MOD/'assets-source/blood_cultist';rawout.mkdir(parents=True,exist_ok=True)
 rates=[11025]*5+[22050]*4+[44100]*4
 for event,ids in EVENTS.items():
  for ident in ids:
   entry=rff.byid[('SFX',ident)];sfx=rff.read(entry)
   volume,pitch,pitch_range,fmt,loop=struct.unpack_from('<5i',sfx)
   rawname=bytes(sfx[20:]).split(b'\0')[0].decode('ascii')
   requested_raw=rawname
   if ('RAW',rawname.upper()) not in rff.byname:
    rawname=rawname+'z' # This retail archive only includes 2008Z/2002Z variants.
   raw=rff.read(rff.byname[('RAW',rawname.upper())])
   (rawout/f'{ident}_{entry[3]}.sfx').write_bytes(sfx)
   (rawout/f'{rawname}.raw').write_bytes(raw)
   rate=rates[fmt];step=rate*(pitch/65536)/22050
   samples=[]
   for n in range(math.ceil(len(raw)/step)):
    position=min(n*step,len(raw)-1);i=int(position);alpha=position-i
    value=(raw[i]-128)*(1-alpha)+(raw[min(i+1,len(raw)-1)]-128)*alpha
    samples.append(max(-32768,min(32767,round(value*256))))
   name=f'blood/cultist/sfx_{ident}.wav';target=MOD/'sound'/name
   with wave.open(str(target),'wb') as w:
    w.setparams((1,2,22050,0,'NONE','not compressed'));w.writeframes(struct.pack('<'+'h'*len(samples),*samples))
   duration=len(samples)/22050
   report.append({'id':ident,'sfx_name':entry[3],'raw':rawname,'requested_raw':requested_raw,'event':event,'family':'fanatic' if ident>=4000 else 'cultist','path':'sound/'+name,'duration':duration,'source_rate':rate,'source_pitch':pitch/65536,'sha256':hashlib.sha256(target.read_bytes()).hexdigest()})
   header.append(f'    {{"{name}",{duration:.6f}f,CultistEvent::{event},{1 if ident>=4000 else 0}}},')
 text='''// Generated by tools/install_blood_cultist_voices.py; paths have static lifetime.
enum class CultistEvent { Alert, Search, Pain, Death, Victory, Burning };
struct CultistVoiceClip {const char* path;float duration;CultistEvent event;int family;};
static constexpr CultistVoiceClip cultistClips[]={
'''+ '\n'.join(header)+'\n};\n'
 (MOD/'source/blood_cultist_assets.h').write_text(text)
 p=MOD/'sound/sentences.txt';original=p.read_text(encoding='cp1252')
 original=re.sub(r'\n// BEGIN BLOOD CULTIST VOICES.*?// END BLOOD CULTIST VOICES\n?', '\n',original,flags=re.S)
 # All native HECU groups are provided, including previously absent idle groups.
 groups={'HG_ALERT':'Alert','HG_MONSTER':'Alert','HG_MONST':'Alert','HG_GREN':'Alert','HG_THROW':'Alert','HG_CHARGE':'Alert','HG_TAUNT':'Alert','HG_COVER':'Search','HG_CHECK':'Search','HG_QUEST':'Search','HG_IDLE':'Search','HG_CLEAR':'Search','HG_ANSWER':'Search','HG_PAIN':'Pain','HG_KILL':'Victory','HG_DIE':'Death','HG_BURN':'Burning'}
 lines=['','// BEGIN BLOOD CULTIST VOICES']
 for group,event in groups.items():
  # Native groups are registered; the server voice hook selects a stable family.
  for i,ident in enumerate(EVENTS[event]):lines.append(f'{group}{i} blood/cultist/sfx_{ident}')
 lines.append('// END BLOOD CULTIST VOICES')
 p.write_text(original.rstrip()+'\n'+'\n'.join(lines)+'\n',encoding='cp1252')
 data={'source_archive':str(BLOOD/'sounds.rff'),'source_sha256':hashlib.sha256((BLOOD/'sounds.rff').read_bytes()).hexdigest(),'sources':['https://github.com/NBlood/NBlood/blob/master/source/blood/src/ai.cpp','https://github.com/NBlood/NBlood/blob/master/source/blood/src/aicult.cpp','https://github.com/NBlood/NBlood/blob/master/source/blood/src/actor.cpp','https://github.com/NBlood/NBlood/blob/master/source/blood/src/resource.h'],'notes':'All 50 available vocal SFX entries, including variants not selected by vanilla random ranges. Gunshots/TNT sounds 1000-1002 and 4000-4002 excluded. Pitch baked from SFX metadata; PCM8 unsigned RAW converted to mono PCM16/22050 Hz. Retail aliases 4023/4024 request missing RAW 2008/2002: use the existing 2008Z/2002Z recordings with their SFX pitch. No invented translations of cultist language.','groups':groups,'clips':report}
 (MOD/'blood-cultist-voices.json').write_text(json.dumps(data,indent=2)+'\n')
 print(f'Installed {len(report)} cultist/fanatic vocal entries and {len(groups)} HECU sentence groups.')
if __name__=='__main__':install()
